CREATE TABLE IF NOT EXISTS campus_resources (
    id BIGINT PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500) NOT NULL,
    location VARCHAR(200) NOT NULL,
    capacity_or_quantity INTEGER NOT NULL CHECK (capacity_or_quantity > 0),
    category VARCHAR(30) NOT NULL,
    availability_status VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS campus_users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('STUDENT', 'CLUB_REPRESENTATIVE', 'ADMIN')),
    department VARCHAR(100),
    year_of_study INTEGER,
    roll_number VARCHAR(40),
    club_name VARCHAR(100),
    registration_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('ACTIVE', 'DISABLED'))
);

-- Booking tables are additive: existing campus_resources and campus_users rows remain untouched.
CREATE TABLE IF NOT EXISTS booking_requests (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(32) UNIQUE,
    requester_id BIGINT NOT NULL REFERENCES campus_users(user_id),
    requester_name VARCHAR(100) NOT NULL,
    requester_role VARCHAR(30) NOT NULL CHECK (requester_role IN ('STUDENT', 'CLUB_REPRESENTATIVE')),
    department VARCHAR(100) NOT NULL,
    club_name VARCHAR(100),
    event_title VARCHAR(150) NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    purpose VARCHAR(1200) NOT NULL,
    event_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    expected_participants INTEGER NOT NULL CHECK (expected_participants > 0),
    special_requirements VARCHAR(1200),
    supporting_information VARCHAR(2000),
    status VARCHAR(40) NOT NULL CHECK (status IN ('PENDING','UNDER_REVIEW','ADDITIONAL_INFORMATION_REQUIRED','ALTERNATIVE_PROPOSED','APPROVED','REJECTED','CANCELLED','COMPLETED')),
    decision_note VARCHAR(1200),
    alternative_date DATE,
    alternative_start_time TIME,
    alternative_end_time TIME,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_time > start_time),
    CHECK (alternative_end_time IS NULL OR alternative_start_time IS NULL OR alternative_end_time > alternative_start_time)
);

CREATE TABLE IF NOT EXISTS booking_request_items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking_requests(booking_id) ON DELETE CASCADE,
    resource_id BIGINT NOT NULL REFERENCES campus_resources(id),
    requested_quantity INTEGER NOT NULL CHECK (requested_quantity > 0),
    UNIQUE (booking_id, resource_id)
);

CREATE TABLE IF NOT EXISTS booking_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking_requests(booking_id) ON DELETE CASCADE,
    status_after VARCHAR(40) NOT NULL CHECK (status_after IN ('PENDING','UNDER_REVIEW','ADDITIONAL_INFORMATION_REQUIRED','ALTERNATIVE_PROPOSED','APPROVED','REJECTED','CANCELLED','COMPLETED')),
    action VARCHAR(40) NOT NULL,
    note VARCHAR(1200),
    changed_by BIGINT NOT NULL REFERENCES campus_users(user_id),
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS equipment_assets (
    asset_tag VARCHAR(40) PRIMARY KEY,
    resource_id BIGINT NOT NULL REFERENCES campus_resources(id),
    asset_status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE' CHECK (asset_status IN ('AVAILABLE','RESERVED','ISSUED','RETURNED','UNDER_MAINTENANCE','LOST','DAMAGED')),
    notes VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS equipment_allocations (
    allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking_requests(booking_id),
    item_id BIGINT NOT NULL REFERENCES booking_request_items(item_id),
    resource_id BIGINT NOT NULL REFERENCES campus_resources(id),
    asset_tag VARCHAR(40) REFERENCES equipment_assets(asset_tag),
    allocated_quantity INTEGER NOT NULL CHECK (allocated_quantity > 0),
    assigned_user_id BIGINT NOT NULL REFERENCES campus_users(user_id),
    issue_time TIMESTAMP,
    expected_return_time TIMESTAMP,
    actual_return_time TIMESTAMP,
    issued_by BIGINT REFERENCES campus_users(user_id),
    returned_by BIGINT REFERENCES campus_users(user_id),
    return_condition VARCHAR(30) CHECK (return_condition IN ('GOOD','MINOR_DAMAGE','DAMAGED','MISSING')),
    equipment_status VARCHAR(30) NOT NULL CHECK (equipment_status IN ('AVAILABLE','RESERVED','ISSUED','RETURNED','UNDER_MAINTENANCE','LOST','DAMAGED')),
    condition_note VARCHAR(500),
    UNIQUE (booking_id, asset_tag)
);

CREATE TABLE IF NOT EXISTS resource_usage_history (
    usage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking_requests(booking_id),
    resource_id BIGINT NOT NULL REFERENCES campus_resources(id),
    requester_role VARCHAR(30) NOT NULL,
    department VARCHAR(100) NOT NULL,
    club_name VARCHAR(100),
    start_at TIMESTAMP NOT NULL,
    end_at TIMESTAMP NOT NULL,
    usage_hours DECIMAL(7,2) NOT NULL CHECK (usage_hours > 0),
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (booking_id, resource_id)
);

CREATE INDEX IF NOT EXISTS idx_booking_date_status ON booking_requests(event_date, status);
CREATE INDEX IF NOT EXISTS idx_booking_requester ON booking_requests(requester_id, created_at);
CREATE INDEX IF NOT EXISTS idx_booking_items_resource ON booking_request_items(resource_id, booking_id);
CREATE INDEX IF NOT EXISTS idx_booking_history ON booking_history(booking_id, changed_at);
CREATE INDEX IF NOT EXISTS idx_equipment_resource_status ON equipment_assets(resource_id, asset_status);
CREATE INDEX IF NOT EXISTS idx_equipment_alloc_booking ON equipment_allocations(booking_id, equipment_status);
CREATE INDEX IF NOT EXISTS idx_resource_usage_rolling ON resource_usage_history(resource_id, recorded_at);

CREATE TABLE IF NOT EXISTS portal_notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL REFERENCES campus_users(user_id) ON DELETE CASCADE,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(1200) NOT NULL,
    notification_type VARCHAR(40) NOT NULL,
    related_booking_id BIGINT REFERENCES booking_requests(booking_id) ON DELETE CASCADE,
    destination_url VARCHAR(500),
    event_key VARCHAR(180) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_portal_notifications_recipient ON portal_notifications(recipient_user_id, created_at);

-- Campus announcements shown on member dashboards, the admin dashboard and /announcements.
CREATE TABLE IF NOT EXISTS campus_announcements (
    announcement_id BIGINT PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    summary VARCHAR(600) NOT NULL,
    body VARCHAR(2000) NOT NULL,
    category VARCHAR(40) NOT NULL,
    image_path VARCHAR(300),
    published_on DATE NOT NULL
);

-- Resource detail pages opened by signed-in students and club representatives ("Recently explored").
CREATE TABLE IF NOT EXISTS resource_views (
    view_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES campus_users(user_id) ON DELETE CASCADE,
    resource_id BIGINT NOT NULL REFERENCES campus_resources(id) ON DELETE CASCADE,
    viewed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_resource_views_user ON resource_views(user_id, viewed_at);

